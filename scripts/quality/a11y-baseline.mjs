/**
 * Regenerate the accessibility adoption baseline from a completed a11y run.
 *
 * Reads `.quality/a11y.json` (the Playwright JSON report the a11y gate writes)
 * and rewrites `apps/storybook/a11y/known-violations.json` with every violation
 * currently outstanding.
 *
 * Run it to RECORD A FIX — the file should only ever get smaller. Running it to
 * turn a red build green defeats the entire mechanism; that is what the `real`
 * bucket in the gate is for.
 *
 *   pnpm quality:a11y || true          # collect, ignoring the failure
 *   node scripts/quality/a11y-baseline.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const REPORT = resolve(root, ".quality/a11y.json");
const OUT = resolve(root, "apps/storybook/a11y/known-violations.json");

if (!existsSync(REPORT)) {
  console.error(`✖ No a11y report at ${REPORT}. Run \`pnpm quality:a11y\` first.`);
  process.exit(1);
}

const report = JSON.parse(readFileSync(REPORT, "utf8"));
const violations = {};

const walk = (suite) => {
  (suite.suites ?? []).forEach(walk);
  for (const spec of suite.specs ?? []) {
    for (const test of spec.tests ?? []) {
      const result = test.results?.at(-1);
      const axe = (result?.attachments ?? []).find((a) => a.name === "axe");
      if (!axe?.body) continue;
      let payload;
      try {
        payload = JSON.parse(Buffer.from(axe.body, "base64").toString("utf8"));
      } catch {
        continue;
      }
      // `violations` are the currently-failing ones; `known` are already
      // baselined and must be carried forward or they would silently drop out.
      const ids = [...(payload.violations ?? []), ...(payload.known ?? [])].map((v) => v.id);
      if (!ids.length) continue;
      violations[payload.storyId] = [
        ...new Set([...(violations[payload.storyId] ?? []), ...ids]),
      ].sort();
    }
  }
};
(report.suites ?? []).forEach(walk);

const ordered = Object.fromEntries(
  Object.entries(violations).sort(([a], [b]) => a.localeCompare(b)),
);
const total = Object.values(ordered).reduce((n, ids) => n + ids.length, 0);

writeFileSync(
  OUT,
  JSON.stringify(
    {
      $comment:
        "GENERATED by scripts/quality/a11y-baseline.mjs — do not edit by hand. " +
        "Every entry is an OPEN accessibility bug, not an accepted exception. " +
        "This file should only ever shrink; regenerate it to record a fix.",
      generatedAt: new Date().toISOString(),
      storiesAffected: Object.keys(ordered).length,
      violationsOpen: total,
      violations: ordered,
    },
    null,
    2,
  ) + "\n",
);

console.log(`✓ ${OUT}`);
console.log(`  ${total} open violation(s) across ${Object.keys(ordered).length} stor(ies)`);
